-- SpendSense core schema: profiles, accounts, categories, transactions.
-- Ownership is enforced twice: RLS (see rls_policies migration) and composite foreign keys
-- (id, user_id) so a row can never reference another user's account/category.

create schema if not exists private;
grant usage on schema private to authenticated, service_role;

-- ---------------------------------------------------------------- enums
create type public.account_type as enum ('cash', 'bank', 'upi', 'card');
create type public.transaction_type as enum ('income', 'expense', 'transfer');
create type public.category_type as enum ('income', 'expense');
create type public.recurrence_frequency as enum ('daily', 'weekly', 'monthly', 'yearly');

-- ---------------------------------------------------------------- helpers
create or replace function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- ---------------------------------------------------------------- profiles
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text check (char_length(full_name) <= 100),
  avatar_url text check (char_length(avatar_url) <= 2048),
  currency char(3) not null default 'INR',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create trigger profiles_set_updated_at
  before update on public.profiles
  for each row execute function private.set_updated_at();

-- ---------------------------------------------------------------- accounts
create table public.accounts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 50),
  type public.account_type not null,
  opening_balance numeric(12, 2) not null default 0,
  -- Derived: opening_balance + effect of all transactions. Maintained by triggers,
  -- any client-supplied value is overwritten.
  balance numeric(12, 2) not null default 0,
  color text not null default '#64748b' check (color ~ '^#[0-9a-fA-F]{6}$'),
  is_archived boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, user_id)
);

create unique index accounts_user_name_key on public.accounts (user_id, lower(name));

create trigger accounts_set_updated_at
  before update on public.accounts
  for each row execute function private.set_updated_at();

-- ---------------------------------------------------------------- categories
create table public.categories (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 40),
  type public.category_type not null,
  icon text not null default 'tag' check (icon ~ '^[a-z0-9-]{1,40}$'),
  color text not null default '#64748b' check (color ~ '^#[0-9a-fA-F]{6}$'),
  is_default boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, user_id)
);

create unique index categories_user_type_name_key
  on public.categories (user_id, type, lower(name));

create trigger categories_set_updated_at
  before update on public.categories
  for each row execute function private.set_updated_at();

-- ---------------------------------------------------------------- transactions
create table public.transactions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  type public.transaction_type not null,
  amount numeric(12, 2) not null check (amount > 0),
  account_id uuid not null,
  -- Destination account, only for transfers.
  to_account_id uuid,
  category_id uuid,
  description text check (char_length(description) <= 200),
  notes text check (char_length(notes) <= 1000),
  date date not null default current_date,
  receipt_url text check (char_length(receipt_url) <= 2048),
  -- True when the user created a recurring rule from this transaction.
  is_recurring_source boolean not null default false,
  -- Set on occurrences generated by a recurring rule (FK added in planning_schema migration).
  recurring_rule_id uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, user_id),
  foreign key (account_id, user_id)
    references public.accounts (id, user_id) on delete restrict,
  foreign key (to_account_id, user_id)
    references public.accounts (id, user_id) on delete restrict,
  foreign key (category_id, user_id)
    references public.categories (id, user_id) on delete set null (category_id),
  constraint transactions_transfer_shape check (
    (type = 'transfer' and to_account_id is not null and to_account_id <> account_id and category_id is null)
    or (type <> 'transfer' and to_account_id is null)
  )
);

create index transactions_user_date_idx on public.transactions (user_id, date desc, created_at desc);
create index transactions_user_category_idx on public.transactions (user_id, category_id);
create index transactions_account_idx on public.transactions (account_id);
create index transactions_to_account_idx on public.transactions (to_account_id) where to_account_id is not null;

create trigger transactions_set_updated_at
  before update on public.transactions
  for each row execute function private.set_updated_at();

-- ---------------------------------------------------------------- balance maintenance
create or replace function private.compute_account_balance(p_account_id uuid, p_opening numeric)
returns numeric
language sql
stable
set search_path = ''
as $$
  select p_opening + coalesce(sum(
    case
      when t.type = 'income' then t.amount
      when t.type = 'expense' then -t.amount
      when t.type = 'transfer' and t.account_id = p_account_id then -t.amount
      when t.type = 'transfer' and t.to_account_id = p_account_id then t.amount
      else 0
    end), 0)
  from public.transactions t
  where t.account_id = p_account_id or t.to_account_id = p_account_id;
$$;

create or replace function private.accounts_sync_balance()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    new.balance := new.opening_balance;
  else
    new.balance := private.compute_account_balance(new.id, new.opening_balance);
  end if;
  return new;
end;
$$;

create trigger accounts_sync_balance
  before insert or update on public.accounts
  for each row execute function private.accounts_sync_balance();

-- Touching the affected accounts re-runs accounts_sync_balance.
create or replace function private.transactions_refresh_balances()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op in ('UPDATE', 'DELETE') then
    update public.accounts set updated_at = now()
    where id in (old.account_id, old.to_account_id);
  end if;
  if tg_op in ('INSERT', 'UPDATE') then
    update public.accounts set updated_at = now()
    where id in (new.account_id, new.to_account_id);
  end if;
  return null;
end;
$$;

create trigger transactions_refresh_balances
  after insert or update or delete on public.transactions
  for each row execute function private.transactions_refresh_balances();
